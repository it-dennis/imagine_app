import { describe, it, expect } from 'vitest'
import { readFileSync } from 'fs'
import { join } from 'path'
import { DIALECTS, checkRoundTrip, detokenize, guessDialect, tokenize, type DialectId } from '../../src/renderer/lib/lang/basic'

const FIXTURES = join(__dirname, '..', 'fixtures', 'oracle')
const corpus = JSON.parse(readFileSync(join(FIXTURES, 'basic-corpus.json'), 'utf-8')) as Record<DialectId, string[]>
const bytes = (a: Uint8Array) => Buffer.from(a).toString('hex')

describe('petcat fixtures (generated by VICE petcat, committed)', () => {
  for (const id of ['v2', 'v35', 'v70'] as const) {
    const d = DIALECTS[id]
    const prg = new Uint8Array(readFileSync(join(FIXTURES, `basic-${id}.prg`)))

    it(`${id}: our tokenizer produces exactly petcat's bytes for the corpus`, () => {
      const mine = tokenize(corpus[id].join('\n'), d)
      expect(mine.errors).toEqual([])
      expect(bytes(mine.prg)).toBe(bytes(prg))
    })

    it(`${id}: petcat's program survives detokenize -> tokenize byte-exact`, () => {
      const rt = checkRoundTrip(prg, d)
      expect(rt.problem).toBeUndefined()
      expect(bytes(tokenize(rt.text, d, rt.loadAddress).prg)).toBe(bytes(prg))
    })

    it(`${id}: listing has one line per corpus line with the same line numbers`, () => {
      const lines = detokenize(prg, d).text.split('\n')
      expect(lines.map((l) => l.split(' ')[0])).toEqual(corpus[id].map((l) => l.split(' ')[0]))
    })
  }
})

describe('ROM rules the tokenizer mirrors', () => {
  const v2 = DIALECTS.v2
  const tok = (src: string, d = v2) => bytes(tokenize(src, d).prg)

  it('TOTAL becomes TO + TAL like on the machine', () => {
    expect(tok('10 total=1')).toBe(bytes(Uint8Array.from([0x01, 0x08, 0x0c, 0x08, 0x0a, 0x00, 0xa4, 0x54, 0x41, 0x4c, 0xb2, 0x31, 0x00, 0x00, 0x00])))
  })

  it('stores ? as the PRINT token (petcat does not, the ROM does)', () => {
    expect(tok('10 ?"x"')).toBe(tok('10 print"x"'))
  })

  it('does not tokenize inside quotes, REM or DATA', () => {
    const rem = tokenize('10 rem print goto', v2).prg
    expect(Array.from(rem.subarray(6, 6 + 1))).toEqual([0x8f])
    expect(rem.includes(0x99)).toBe(false) // PRINT stays literal text after REM
    const data = tokenize('10 data print,"goto":print', v2).prg
    expect(data.filter((b) => b === 0x99)).toHaveLength(1) // only the PRINT after the colon
    expect(data.includes(0x89)).toBe(false)
  })

  it('regenerates link pointers from the load address', () => {
    const a = tokenize('10 print\n20 end', v2, 0x0801).prg
    const b = tokenize('10 print\n20 end', v2, 0x1c01).prg
    expect(a[2] | (a[3] << 8)).toBe(0x0801 + 4 + 1 + 1) // line 10 = 4 header + PRINT + 0
    expect(b[2] | (b[3] << 8)).toBe(0x1c01 + 4 + 1 + 1)
  })

  it('BASIC 7.0: DOPEN is one two-byte token, not DO + PEN', () => {
    const t = tokenize('10 dopen#1,"f"', DIALECTS.v70).prg
    expect(Array.from(t.subarray(6, 8))).toEqual([0xfe, 0x0d])
  })

  it('accepts lowercase and the pi character', () => {
    expect(tok('10 PRINT PI')).toBe(tok('10 print pi'))
    expect(tok('10 a=π')).toContain('ff')
  })
})

describe('lossless text form', () => {
  const v2 = DIALECTS.v2
  /** Builds a one-line PRG with an arbitrary body for round-trip tests. */
  const prgOf = (body: number[], load = 0x0801) => {
    const next = load + 4 + body.length + 1
    return Uint8Array.from([load & 255, load >> 8, next & 255, next >> 8, 10, 0, ...body, 0, 0, 0])
  }

  it('every byte value survives inside a string', () => {
    const all = Array.from({ length: 256 }, (_, i) => i).filter((b) => b !== 0 && b !== 0x22)
    const prg = prgOf([0x99, 0x22, ...all, 0x22])
    const rt = checkRoundTrip(prg, v2)
    expect(rt.problem).toBeUndefined()
    expect(bytes(tokenize(rt.text, v2, rt.loadAddress).prg)).toBe(bytes(prg))
  })

  it('shows control codes by name and the rest as {$xx}', () => {
    const text = detokenize(prgOf([0x99, 0x22, 0x93, 0x11, 0x12, 0x61, 0xc1, 0x22]), v2).text
    expect(text).toBe('10 PRINT"{clr}{down}{rvon}{$61}{$c1}"')
  })

  it('bytes in REM and DATA that look like tokens stay bytes', () => {
    for (const body of [[0x8f, 0x20, 0x99, 0x89], [0x83, 0x99, 0x2c, 0x31], [0x83, 0x22, 0x3a, 0x22, 0x3a, 0x99]]) {
      const prg = prgOf(body)
      const rt = checkRoundTrip(prg, v2)
      expect(rt.problem, `body ${body.map((b) => b.toString(16))}`).toBeUndefined()
      expect(bytes(tokenize(rt.text, v2).prg)).toBe(bytes(prg))
    }
  })

  it('a stored space right after the line number is kept as {$20}', () => {
    const prg = prgOf([0x20, 0x99])
    expect(detokenize(prg, v2).text).toBe('10 {$20}PRINT')
    expect(checkRoundTrip(prg, v2).problem).toBeUndefined()
  })

  it('unassigned tokens use {$xx}', () => {
    const prg = prgOf([0xcc, 0xfe])
    expect(detokenize(prg, v2).text).toBe('10 {$cc}{$fe}')
    expect(checkRoundTrip(prg, v2).problem).toBeUndefined()
  })

  it('keeps an unterminated string byte-exact', () => {
    const prg = prgOf([0x99, 0x22, 0x41, 0x42])
    expect(checkRoundTrip(prg, v2).problem).toBeUndefined()
  })
})

describe('files that must not be edited as plain BASIC text', () => {
  const v2 = DIALECTS.v2
  it('flags machine code after the program', () => {
    const base = tokenize('10 sys 2064', v2).prg
    const withMl = Uint8Array.from([...base, 0xa9, 0x00, 0x60])
    const rt = checkRoundTrip(withMl, v2)
    expect(rt.problem).toBe('trailer')
    expect(rt.trailerBytes).toBe(3)
  })

  it('flags damaged line chains', () => {
    expect(checkRoundTrip(Uint8Array.from([0x01, 0x08, 0x10, 0x08, 0x0a]), v2).problem).toBe('malformed')
  })

  it('flags raw keyword letters that would be re-tokenized', () => {
    // bytes "PRINT" typed as letters (no token): cannot be shown as text without changing them
    const raw = Uint8Array.from([0x01, 0x08, 0x0c, 0x08, 0x0a, 0x00, 0x50, 0x52, 0x49, 0x4e, 0x54, 0x00, 0x00, 0x00])
    expect(checkRoundTrip(raw, v2).problem).toBe('not-lossless')
  })
})

describe('tokenize error reporting', () => {
  const v2 = DIALECTS.v2
  it('reports lines without a number', () => {
    expect(tokenize('print "x"', v2).errors[0]).toMatchObject({ line: 1, message: expect.stringMatching(/Zeilennummer/) })
  })
  it('reports line numbers above 63999', () => {
    expect(tokenize('64000 end', v2).errors).toHaveLength(1)
  })
  it('reports characters that PETSCII cannot show and unknown escapes', () => {
    expect(tokenize('10 print "€"', v2).errors[0].message).toMatch(/nicht darstellbar/)
    expect(tokenize('10 print "{nonsense}"', v2).errors[0].message).toMatch(/Unbekannt/)
  })
  it('warns (but still builds) for unsorted line numbers', () => {
    const r = tokenize('20 end\n10 end', v2)
    expect(r.errors).toEqual([])
    expect(r.warnings).toHaveLength(1)
  })
  it('keeps very long lines intact and only warns', () => {
    const r = tokenize(`10 print "${'x'.repeat(300)}"`, v2)
    expect(r.errors).toEqual([])
    expect(r.warnings[0].message).toMatch(/Bytes lang/)
    expect(r.prg.length).toBeGreaterThan(300)
  })
  it('skips blank lines', () => {
    expect(tokenize('\n10 end\n\n20 end\n', v2).errors).toEqual([])
  })
})

describe('guessDialect', () => {
  it('uses the load address and the disk system', () => {
    expect(guessDialect(0x0801)).toBe('v2')
    expect(guessDialect(0x1c01)).toBe('v70')
    expect(guessDialect(0x1001, 'plus4')).toBe('v35')
    expect(guessDialect(0x1001, 'vic20')).toBe('v2')
    expect(guessDialect(0x1201, 'vic20')).toBe('v2')
  })
})
