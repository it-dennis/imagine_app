// Generates src/renderer/lib/lang/basic-tokens.ts from VICE's petcat, so the BASIC token tables come from
// an independent tool instead of memory. Usage: node scripts/gen-basic-tokens.mjs [--check]
//   --check  regenerate in memory and fail if the committed file differs (used by the oracle test).
import { spawnSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(ROOT, 'src/renderer/lib/lang/basic-tokens.ts')
const PETCAT = [process.env.IMAGINE_VICE_DIR, 'C:\\Program Files\\Vice', 'C:\\Program Files\\GTK3VICE', '/usr/bin', '/usr/local/bin']
  .filter(Boolean)
  .map((d) => join(d, process.platform === 'win32' ? 'petcat.exe' : 'petcat'))
  .find(existsSync)
if (!PETCAT) {
  console.error('petcat not found (set IMAGINE_VICE_DIR)')
  process.exit(2)
}

// id -> petcat version switch and the label shown in the editor
const VERSIONS = [
  { id: 'v2', petcat: '2', label: 'BASIC V2 (C64 / VIC-20)' },
  { id: 'v35', petcat: '3', label: 'BASIC 3.5 (Plus/4, C16)' },
  { id: 'v70', petcat: '70', label: 'BASIC 7.0 (C128)' },
]

const tmp = mkdtempSync(join(tmpdir(), 'gen-tokens-'))
const run = (args) => spawnSync(PETCAT, args, { encoding: 'buffer' })

function keywords(version) {
  const text = run([`-k${version}`]).stdout.toString('latin1').replace(/\r/g, '')
  const lines = text.split('\n').slice(1).filter((l) => l.trim() !== '' && !l.includes('Available Keywords'))
  // each line is one token group: main table first, then prefixed groups
  return lines.flatMap((l) => l.split('\t')).filter((k) => k !== '' && k.trim() !== '')
}

function tokenize(version, source) {
  const inFile = join(tmp, 'in.txt')
  const outFile = join(tmp, 'out.prg')
  writeFileSync(inFile, source + '\n')
  run([`-w${version}`, '-f', '-o', outFile, '--', inFile])
  return readFileSync(outFile)
}

const out = []
for (const v of VERSIONS) {
  const probe = tokenize(v.petcat, '10 rem')
  const loadAddress = probe[0] | (probe[1] << 8)
  const seen = new Set()
  const tokens = []
  for (const kw of keywords(v.petcat)) {
    const name = kw.toUpperCase()
    if (seen.has(name)) continue
    seen.add(name)
    const prg = tokenize(v.petcat, `10 ${kw}`)
    // layout: load(2) link(2) line(2) <token bytes> 00 00 00
    const body = [...prg.subarray(6)]
    const end = body.indexOf(0)
    const bytes = body.slice(0, end)
    if (bytes.length < 1 || bytes.length > 2 || bytes[0] < 0x80) {
      throw new Error(`petcat ${v.id}: keyword "${kw}" did not tokenize to a token (got ${bytes.map((b) => b.toString(16))})`)
    }
    tokens.push({ text: name, bytes })
  }
  // petcat lists pi as "~"; BASIC accepts the pi character for the same token
  const pi = tokens.find((t) => t.text === '~')
  if (pi) tokens.push({ text: '\u03c0', bytes: pi.bytes })
  out.push({ ...v, loadAddress, tokens })
}
rmSync(tmp, { recursive: true, force: true })

const hex = (b) => '0x' + b.toString(16).padStart(2, '0')
const body = out
  .map(
    (v) => `  ${v.id}: {
    id: '${v.id}',
    label: '${v.label}',
    loadAddress: 0x${v.loadAddress.toString(16).padStart(4, '0')},
    tokens: [
${v.tokens.map((t) => `      { text: ${JSON.stringify(t.text)}, bytes: [${t.bytes.map(hex).join(', ')}] },`).join('\n')}
    ],
  },`,
  )
  .join('\n')

const ts = `// GENERATED by scripts/gen-basic-tokens.mjs from VICE petcat. Do not edit by hand; regenerate instead.
// Token order is the keyword table order of the dialect.

export interface TokenDef {
  text: string
  bytes: number[]
}

export interface DialectData {
  id: 'v2' | 'v35' | 'v70'
  label: string
  /** Default PRG load address petcat uses for this dialect. */
  loadAddress: number
  tokens: TokenDef[]
}

export const DIALECT_DATA: Record<DialectData['id'], DialectData> = {
${body}
}
`

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf-8') : ''
  if (current.replace(/\r\n/g, '\n') !== ts) {
    console.error('basic-tokens.ts is out of date; run: node scripts/gen-basic-tokens.mjs')
    process.exit(1)
  }
  console.log('basic-tokens.ts is up to date')
} else {
  writeFileSync(OUT, ts)
  console.log(`wrote ${OUT}: ${out.map((v) => `${v.id}=${v.tokens.length}`).join(', ')}`)
}
